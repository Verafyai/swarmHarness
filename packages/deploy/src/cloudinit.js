/**
 * The first-boot script for a cloud server (DigitalOcean, Hetzner, or any
 * provider that takes user data). It installs Node 22, fetches Verafy Harness
 * at a pinned ref, writes the harness's environment to /etc/verafy/env (mode
 * 600), optionally installs Ollama and pulls an open-weights model, and runs
 * the daemon as a systemd service that restarts on failure.
 *
 * The harness's signing key is made on the server at first start and never
 * leaves it. The model key, if any, is in the user data: cloud providers keep
 * user data in the server's metadata, readable from inside the server and by
 * the account, so use a key scoped to this harness, with a spending limit.
 *
 * @module @verafyharness/deploy/cloudinit
 */

export const REPO = 'https://github.com/Verafyai/verafyHarness.git'

/** Shell-quote one value for a single-quoted context. */
export function sq(v) {
  return `'${String(v).replace(/'/g, `'\\''`)}'`
}

const ENV_NAME = /^[A-Z][A-Z0-9_]*$/

/**
 * @param {object} o
 * @param {Record<string, string>} o.env - VERAFY_* variables for the harness (see config.js).
 * @param {string} [o.ref] - git ref to run (a tag such as v0.0.2-alpha, or main).
 * @param {string} [o.ollamaTag] - pull and serve this open-weights model locally.
 * @param {'digitalocean'|'hetzner'|'generic'} [o.cloud] - how to find the public IP.
 * @returns {string} a bash user-data script.
 */
export function cloudInit({ env, ref = 'main', ollamaTag = null, cloud = 'generic' }) {
  for (const k of Object.keys(env)) if (!ENV_NAME.test(k)) throw new Error(`bad variable name: ${k}`)
  if (!/^[\w./-]+$/.test(ref)) throw new Error('bad git ref')
  if (ollamaTag && !/^[\w.:-]+$/.test(ollamaTag)) throw new Error('bad model tag')
  const ip = {
    digitalocean: 'curl -fsS http://169.254.169.254/metadata/v1/interfaces/public/0/ipv4/address',
    hetzner: 'curl -fsS http://169.254.169.254/hetzner/v1/metadata/public-ipv4',
    generic: 'curl -fsS https://api.ipify.org',
  }[cloud]
  const port = env.VERAFY_PORT ?? '7200'
  const lines = Object.entries(env).map(([k, v]) => `${k}=${sq(v)}`)
  return `#!/bin/bash
# Verafy Harness first boot. Generated by \`verafy up\`.
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get install -y ca-certificates curl git ufw
curl -fsSL https://deb.nodesource.com/setup_22.x | bash -
apt-get install -y nodejs
id verafy >/dev/null 2>&1 || useradd --system --create-home --home-dir /var/lib/verafy --shell /usr/sbin/nologin verafy
git clone --depth 1 --branch ${ref} ${REPO} /opt/verafy-harness
chown -R verafy:verafy /opt/verafy-harness
${ollamaTag ? `curl -fsSL https://ollama.com/install.sh | sh
systemctl enable --now ollama
for i in $(seq 1 30); do curl -fsS http://127.0.0.1:11434/api/version >/dev/null && break; sleep 2; done
ollama pull ${ollamaTag}
` : ''}install -d -m 700 -o verafy -g verafy /etc/verafy /var/lib/verafy/data
PUBLIC_IP=$(${ip} || hostname -I | awk '{print $1}')
umask 077
cat > /etc/verafy/env <<'VERAFY_ENV'
${lines.join('\n')}
VERAFY_DATA_DIR=/var/lib/verafy/data
VERAFY_ENV
grep -q '^VERAFY_PUBLIC_URL=' /etc/verafy/env || echo "VERAFY_PUBLIC_URL=http://$PUBLIC_IP:${port}" >> /etc/verafy/env
chown verafy:verafy /etc/verafy/env
cat > /etc/systemd/system/verafy-harness.service <<'UNIT'
[Unit]
Description=Verafy Harness daemon
After=network-online.target${ollamaTag ? ' ollama.service' : ''}
Wants=network-online.target

[Service]
User=verafy
EnvironmentFile=/etc/verafy/env
WorkingDirectory=/opt/verafy-harness
ExecStart=/usr/bin/node bin/verafy.js harness serve
Restart=always
RestartSec=5
NoNewPrivileges=true
ProtectSystem=strict
ReadWritePaths=/var/lib/verafy
PrivateTmp=true

[Install]
WantedBy=multi-user.target
UNIT
ufw allow OpenSSH
ufw allow ${port}/tcp
ufw --force enable
systemctl daemon-reload
systemctl enable --now verafy-harness
`
}
