#!/usr/bin/env node
/**
 * The scoring pass: check every requirement in docs/spec/requirements.json
 * against the repo, score each area, and list the gaps.
 *
 *   node scripts/score.mjs                 print the scorecard
 *   node scripts/score.mjs --write         also write docs/spec/SCORECARD.md and the
 *                                          requirement tables inside VERAFY-SPEC.md
 *   node scripts/score.mjs --check         fail on a bad requirements file or a claim
 *                                          whose checks fail (used by npm test)
 *   node scripts/score.mjs --json          machine-readable output
 *   --chain=<path>                         a verafyChain checkout (default: $VERAFY_CHAIN_DIR,
 *                                          then ../verafyChain, then ../verafychain-repo)
 *
 * A requirement earns the points of its status (verified 1.0, built 0.8,
 * partial 0.5, designed 0.25, planned 0.1, research 0) only if all its checks
 * pass. A failed check scores it 0 and flags the claim. Checks in the
 * verafyChain repo are skipped, and flagged, when no checkout is found.
 */
import { readFileSync, existsSync, writeFileSync } from 'node:fs'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const args = process.argv.slice(2)
const has = f => args.includes(f)
const opt = k => args.find(a => a.startsWith(`--${k}=`))?.split('=').slice(1).join('=')

const SPEC = JSON.parse(readFileSync(join(ROOT, 'docs/spec/requirements.json'), 'utf8'))
const testScript = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).scripts?.test ?? ''
const chainDir = [opt('chain'), process.env.VERAFY_CHAIN_DIR, join(ROOT, '../verafyChain'), join(ROOT, '../verafychain-repo')].find(p => p && existsSync(join(p, 'package.json')))

function problems() {
  const errs = []
  const ids = new Set()
  for (const r of SPEC.requirements) {
    if (!/^[A-Z]+-\d{3}$/.test(r.id)) errs.push(`${r.id}: bad id`)
    if (ids.has(r.id)) errs.push(`${r.id}: duplicate id`)
    ids.add(r.id)
    if (!SPEC.areas[r.area]) errs.push(`${r.id}: unknown area ${r.area}`)
    if (!r.id.startsWith(r.area + '-')) errs.push(`${r.id}: id does not match area ${r.area}`)
    if (!SPEC.levels[r.status]) errs.push(`${r.id}: unknown status ${r.status}`)
    if (!(r.weight >= 1 && r.weight <= 3)) errs.push(`${r.id}: weight must be 1 to 3`)
    if (['verified', 'built', 'partial'].includes(r.status) && !r.checks.length) errs.push(`${r.id}: a ${r.status} claim needs at least one check`)
  }
  return errs
}

function runCheck(c) {
  const base = c.repo === 'chain' ? chainDir : ROOT
  if (!base) return { ok: null, why: 'verafyChain checkout not found' }
  if (c.file) return existsSync(join(base, c.file)) ? { ok: true } : { ok: false, why: `missing ${c.file}` }
  if (c.grep) {
    const p = join(base, c.grep)
    if (!existsSync(p)) return { ok: false, why: `missing ${c.grep}` }
    return new RegExp(c.re, 'i').test(readFileSync(p, 'utf8')) ? { ok: true } : { ok: false, why: `${c.grep} lacks /${c.re}/` }
  }
  if (c.test) {
    if (!existsSync(join(base, c.test))) return { ok: false, why: `missing test ${c.test}` }
    return testScript.includes(c.test) ? { ok: true } : { ok: false, why: `${c.test} is not in npm test` }
  }
  return { ok: false, why: 'unknown check' }
}

function score() {
  const rows = SPEC.requirements.map(r => {
    const results = r.checks.map(runCheck)
    const failed = results.filter(x => x.ok === false)
    const skipped = results.filter(x => x.ok === null)
    const claimed = SPEC.levels[r.status].points
    const points = failed.length ? 0 : claimed
    return { ...r, claimed, points, failed: failed.map(f => f.why), unverified: skipped.length > 0 }
  })
  const areas = {}
  for (const a of Object.keys(SPEC.areas)) {
    const rs = rows.filter(r => r.area === a)
    const w = rs.reduce((s, r) => s + r.weight, 0)
    areas[a] = { name: SPEC.areas[a], count: rs.length, score: w ? rs.reduce((s, r) => s + r.weight * r.points, 0) / w : 0 }
  }
  const W = rows.reduce((s, r) => s + r.weight, 0)
  const overall = rows.reduce((s, r) => s + r.weight * r.points, 0) / W
  const gaps = rows.filter(r => r.points < 1).map(r => ({ ...r, impact: r.weight * (1 - r.points) })).sort((a, b) => b.impact - a.impact || a.id.localeCompare(b.id))
  const byStatus = {}
  for (const r of rows) byStatus[r.status] = (byStatus[r.status] ?? 0) + 1
  return { version: SPEC.version, date: SPEC.date, chainChecked: Boolean(chainDir), overall, areas, rows, gaps, byStatus }
}

const pct = x => `${Math.round(x * 100)}%`
const bar = x => '█'.repeat(Math.round(x * 20)).padEnd(20, '░')

function markdown(s) {
  const L = []
  L.push(`# Scorecard, v${s.version}`, '')
  L.push(`Generated by \`npm run score -- --write\` from [requirements.json](requirements.json). Do not edit by hand.`, '')
  L.push(`**Overall: ${pct(s.overall)}** of the spec, weighted. ${s.rows.length} requirements: ` + Object.entries(s.byStatus).map(([k, v]) => `${v} ${k}`).join(', ') + '.', '')
  L.push('A requirement scores its status (verified 100%, built 80%, partial 50%, designed 25%, planned 10%, research 0%) only if every check passes. A score is how far the build is along the spec, not a measure of quality.', '')
  if (!s.chainChecked) L.push('> verafyChain checks were skipped: no checkout found. Those claims are flagged unverified.', '')
  L.push('| Area | Requirements | Score | |', '|---|---|---|---|')
  for (const [k, a] of Object.entries(s.areas)) L.push(`| ${k}: ${a.name} | ${a.count} | ${pct(a.score)} | \`${bar(a.score)}\` |`)
  L.push('', '## Gaps, by impact', '', 'Impact is weight times the points still missing. Needs Rex marks a decision only Rex can make.', '')
  L.push('| ID | Status | Requirement | Gap |', '|---|---|---|---|')
  for (const g of s.gaps) L.push(`| ${g.id} | ${g.status}${g.rex ? ', needs Rex' : ''}${g.failed.length ? ', **check failed**' : ''}${g.unverified ? ', unverified' : ''} | ${g.title} | ${g.failed.length ? g.failed.join('; ') : g.gap ?? ''} |`)
  return L.join('\n') + '\n'
}

function areaTable(s, area) {
  const L = ['| ID | Status | Requirement |', '|---|---|---|']
  for (const r of s.rows.filter(r => r.area === area)) L.push(`| ${r.id} | ${r.status}${r.rex ? ' (needs Rex)' : ''} | ${r.title}${r.gap ? `. *Gap: ${r.gap}.*` : ''} |`)
  return L.join('\n')
}

const errs = problems()
if (errs.length) { console.error(errs.join('\n')); process.exit(1) }
const s = score()

if (has('--json')) console.log(JSON.stringify(s, null, 2))
else {
  console.log(`Verafy spec v${s.version}: ${pct(s.overall)} overall (${s.rows.length} requirements)`)
  for (const [k, a] of Object.entries(s.areas)) console.log(`  ${k.padEnd(7)} ${bar(a.score)} ${pct(a.score).padStart(4)}  ${a.name}`)
  const failed = s.rows.filter(r => r.failed.length)
  if (failed.length) console.log('\nClaims whose checks failed:\n' + failed.map(r => `  ${r.id}: ${r.failed.join('; ')}`).join('\n'))
  console.log(`\nTop gaps:\n` + s.gaps.slice(0, 10).map(g => `  ${g.id} (${g.status}${g.rex ? ', needs Rex' : ''}) ${g.title}`).join('\n'))
}

if (has('--write')) {
  writeFileSync(join(ROOT, 'docs/spec/SCORECARD.md'), markdown(s))
  const specPath = join(ROOT, 'docs/spec/VERAFY-SPEC.md')
  let spec = readFileSync(specPath, 'utf8')
  for (const a of Object.keys(SPEC.areas)) {
    const re = new RegExp(`(<!-- reqs:${a} -->)[\\s\\S]*?(<!-- /reqs:${a} -->)`)
    spec = spec.replace(re, `$1\n${areaTable(s, a)}\n$2`)
  }
  spec = spec.replace(/(<!-- score -->)[\s\S]*?(<!-- \/score -->)/, `$1\n**Scored ${pct(s.overall)} overall** at v${s.version} (see [SCORECARD.md](SCORECARD.md)).\n$2`)
  writeFileSync(specPath, spec)
}

if (has('--check')) {
  const spec = existsSync(join(ROOT, 'docs/spec/VERAFY-SPEC.md')) ? readFileSync(join(ROOT, 'docs/spec/VERAFY-SPEC.md'), 'utf8') : ''
  const missing = Object.keys(SPEC.areas).filter(a => !spec.includes(`<!-- reqs:${a} -->`))
  const failed = s.rows.filter(r => r.failed.length)
  if (missing.length || failed.length) {
    if (missing.length) console.error(`spec is missing sections for: ${missing.join(', ')}`)
    if (failed.length) console.error(`claims not backed by their checks: ${failed.map(r => r.id).join(', ')}`)
    process.exit(1)
  }
}
